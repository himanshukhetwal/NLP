#NLP Project (Pipeline -> Text Cleaning)

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv('train.txt',sep=';',header=None, names=['text','emotions']) #in csv file we dont have comas so
#what we did here is we read our txt file as csv file and separated it with the comas
#and created two cols text and emotions

df.head()

df.isnull().sum() #to check whether we have null values or not

#now checking how many unique emotions we have
df['emotions'].unique()

#now creating a dictionory where these emotions are converted into 0 based indexing
unique_emotions= df['emotions'].unique() #first created a array
emotion_numbers={}
i=0
for emo in unique_emotions:
    emotion_numbers[emo]=i
    i=i+1
df['emotions']=df['emotions'].map(emotion_numbers)

df

#converting all texts in lower case
df['text'] = df['text'].apply(lambda x: x.lower())
df

#Removing punctuations
import string
def remove_punc(txt):
  return txt.translate(str.maketrans('','',string.punctuation))
df['text'] = df['text'].apply(remove_punc)

# Remove numbers
def remove_num(txt):
  new=""
  for i in txt:
    if not i.isdigit():
      new=new+i
  return new
df['text'] = df['text'].apply(remove_num)

# Remove emogis and special char
def remove_emojis(txt):
  new=""
  for i in txt:
    if i.isascii(): # move data to new only if i has a ascii value and as emojis dont have any ascii value it will be terminated
      new=new+i
  return new
df['text'] = df['text'].apply(remove_emojis)

# Remove stopwords
# to remove the stopwords we have to use a library and that is NLTK
import nltk
from nltk.corpus import stopwords
from nltk.tokenize import word_tokenize
nltk.download('stopwords')
nltk.download('punkt')# is a library which toeknizes your words (means simply , it is used for tokenization)

# to see the set of stopwords
stop_words = set(stopwords.words('english'))
stop_words

len(stop_words)

#now removing stop words
df.loc[1]['text'] # to see the data

# as we have the list of stop words and will convert it into array
def remove(txt):
  words = txt.split() #here we have to use word_tokenize instead of split (we are using split as it is giving some error in google colab)
  cleaned = []
  for i in words:
    if not i in stop_words:
      cleaned.append(i)
  return ' '.join(cleaned)
df['text'] = df['text'].apply(remove)
# note: split and tokenize are both diff

# now seeing the same sentence after removing stopwords
