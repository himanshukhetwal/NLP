#doing train_test split
from sklearn.model_selection import train_test_split
X_train,X_test,y_train,y_test = train_test_split(df['text'],df['emotions'],test_size=0.2,random_state=42)

X_train

X_test

# vectorization (converting x_train and x_test into vectors)
from sklearn.feature_extraction.text import TfidfVectorizer, CountVectorizer

#first doing with count vectorizer(bag of words)
cv = CountVectorizer()
X_train_cv = cv.fit_transform(X_train)
X_test_cv = cv.transform(X_test)

from sklearn.naive_bayes import MultinomialNB # for text classification we use Myultinomial Naive Bayes algo
from sklearn.metrics import accuracy_score
model = MultinomialNB()
model.fit(X_train_cv,y_train)

y_pred = model.predict(X_test_cv)
print(accuracy_score(y_test,y_pred))

